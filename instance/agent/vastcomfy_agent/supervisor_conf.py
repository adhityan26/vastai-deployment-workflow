from __future__ import annotations

import re

from .config import Config, ConfigError

# supervisord is already running (the image's own) and does not see our environment, so the
# program definitions carry literal values. Its parser splits the command on whitespace and
# expands %(...)s, so a value with either would silently change meaning: reject it instead.
_UNSAFE = re.compile(r"[\s%]")

_KEYS = ("TAILSCALED_BIN", "TS_SOCKET", "STATE_DIR", "AGENT_PYTHON", "ENV_FILE_PATH", "REPO_DIR")


def _literal(cfg: Config, key: str) -> str:
    value = str(cfg.get(key))
    if value == "" or _UNSAFE.search(value):
        raise ConfigError(f"{key}: must be non-empty and contain no whitespace or '%' (supervisor would reparse it)")
    return value


def render(cfg: Config) -> str:
    v = {key: _literal(cfg, key) for key in _KEYS}
    tailscaled = (
        f"{v['TAILSCALED_BIN']} --tun=userspace-networking "
        f"--state={v['STATE_DIR']}/tailscale/tailscaled.state --socket={v['TS_SOCKET']}"
    )
    agent = f"{v['AGENT_PYTHON']} -m vastcomfy_agent --env-file {v['ENV_FILE_PATH']}"
    lines = [
        "; generated by vastcomfy_agent.boot render-supervisor-conf; do not edit",
        "[program:tailscaled]",
        f"command={tailscaled}",
        "autostart=false",
        "autorestart=true",
        "",
        "[program:agent]",
        f"command={agent}",
        f"directory={v['REPO_DIR']}/instance/agent",
        "autostart=false",
        "autorestart=true",
        "startsecs=1",
        "startretries=10",
        "",
    ]
    return "\n".join(lines)
