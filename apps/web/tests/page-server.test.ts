import { afterEach, describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { FastifyInstance } from "fastify";
import type { AppsConfig } from "@vast-comfy/core";
import { buildServer } from "../src/server.js";

// The page is served by the real server and must work under its Content-Security-Policy.

const publicDir = fileURLToPath(new URL("../public", import.meta.url));
const cfg = {
  webBodyLimitBytes: 4096,
  webRequestTimeoutS: 30,
  webConnectionTimeoutS: 60,
  webKeepaliveTimeoutS: 75,
  startRateLimitPerHour: 2,
  webGenerateRateLimitPerHour: 5,
  webJobCacheMax: 10,
  webJobTtlS: 60,
  generateTimeoutS: 60,
  webExtendMaxMinutes: 60,
} as unknown as AppsConfig;

const apps: FastifyInstance[] = [];
afterEach(async () => {
  for (const a of apps.splice(0)) await a.close();
});

async function server(): Promise<FastifyInstance> {
  const app = buildServer({
    cfg,
    auth: { identify: async () => null, role: () => "none" },
    lifecycle: {} as never,
    registry: { active: async () => null },
    comfyFor: () => ({}) as never,
    profile: {} as never,
    template: {},
    publicDir,
    secrets: () => [],
  });
  apps.push(app);
  await app.ready();
  return app;
}

const html = () => readFileSync(`${publicDir}/index.html`, "utf8");

describe("GET / under the strict CSP", () => {
  it("serves the page with the CSP and no-store-friendly headers", async () => {
    const app = await server();
    const res = await app.inject({ method: "GET", url: "/" });
    expect(res.statusCode).toBe(200);
    expect(res.headers["content-type"]).toContain("text/html");
    const csp = String(res.headers["content-security-policy"]);
    expect(csp).toContain("script-src 'self'");
    expect(csp).toContain("style-src 'self'");
    expect(csp).not.toContain("unsafe-inline");
    expect(csp).not.toContain("unsafe-eval");
    expect(res.body).toBe(html());
  });

  it("references only same-origin files, and the server can serve each of them", async () => {
    const app = await server();
    const refs = [...html().matchAll(/(?:src|href)="([^"]+)"/g)].map((m) => m[1]!);
    expect(refs.length).toBeGreaterThan(0);
    for (const ref of refs) {
      expect(ref.startsWith("/") && !ref.startsWith("//"), `${ref} must be a same-origin path`).toBe(true);
      const file = ref === "/app.js" ? "app.js" : ref.slice(1);
      if (file === "app.js") continue; // generated by `npm run build:page`
      const res = await app.inject({ method: "GET", url: ref });
      expect(res.statusCode, ref).toBe(200);
    }
    const manifest = await app.inject({ method: "GET", url: "/manifest.webmanifest" });
    expect(manifest.statusCode).toBe(200);
    expect(JSON.parse(manifest.body).start_url).toBe("/");
  });

  it("serves the bundled script as javascript when it has been built", async () => {
    const app = await server();
    const res = await app.inject({ method: "GET", url: "/app.js" });
    if (res.statusCode === 404) return; // not built in this checkout
    expect(res.headers["content-type"]).toContain("javascript");
  });
});

describe("index.html is CSP-clean", () => {
  it("has no inline script content, inline handlers or inline styles", () => {
    const doc = html();
    for (const m of doc.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
      expect(m[1], "script must load a file").toMatch(/\bsrc="/);
      expect(m[2]!.trim(), "script must be empty").toBe("");
    }
    expect(doc).not.toMatch(/<[^>]+\son[a-z]+\s*=/i);
    expect(doc).not.toMatch(/<style\b/i);
    expect(doc).not.toMatch(/\sstyle\s*=/i);
    expect(doc).not.toMatch(/javascript:/i);
    expect(doc).not.toMatch(/https?:\/\//i);
  });

  it("carries the home-screen metadata", () => {
    const doc = html();
    expect(doc).toContain('rel="manifest"');
    expect(doc).toContain('name="theme-color"');
    expect(doc).toContain('name="apple-mobile-web-app-capable"');
    expect(doc).toContain('rel="apple-touch-icon"');
  });
});
